    /**
     * @param  array<string, string>  $rule
     */
    public function natRule(array $rule): string
    {
        $attributes = [
            'chain' => 'dstnat',
            'action' => 'dst-nat',
            'protocol' => $rule['protocol'],
            'dst-address' => $rule['dst-address'],
            'dst-port' => $rule['dst-port'],
            'to-addresses' => $rule['to-addresses'],
            'to-ports' => $rule['to-ports'],
            'comment' => $rule['comment'],
            'disabled' => 'no',
        ];

        $parts = [];
        foreach ($attributes as $key => $value) {
            $parts[] = $key.'='.$this->quote($value);
        }

        return "# DST-NAT generated by Simple VPN NAT\n/ip firewall nat add ".implode(' ', $parts)."\n";
    }

    public function sstpSpeedtestClient(
        string $username,
        string $password,
        string $connectTo,
        string $gateway,
    ): string {
        $interface = 'sstp-out1';
        $table = 'Speedtest';
        $mangleComment = 'RUTING Speedtest';
        $routeComment = 'Speedtest via '.$interface;
        $lines = [
            '# SSTP client and Speedtest routing generated by Simple VPN NAT',
            '# verify-server-certificate=no disables server certificate validation.',
            ':if ([:len [/interface sstp-client find where name='.$this->quote($interface).']] = 0) do={ /interface sstp-client add name='.$this->quote($interface).' connect-to='.$this->quote($connectTo).' user='.$this->quote($username).' password='.$this->quote($password).' authentication=mschap2 verify-server-certificate=no disabled=no }',
            ':if ([:len [/routing table find where name='.$this->quote($table).']] = 0) do={ /routing table add name='.$this->quote($table).' fib }',
        ];

        foreach (self::LOCAL_NETWORKS as $address) {
            $lines[] = $this->addressListAdd('IP-Lokal', $address);
        }

        foreach (self::SPEEDTEST_ADDRESSES as $entry) {
            $lines[] = $this->addressListAdd('speedtest', $entry['address'], $entry['comment'] ?? null);
        }

        $lines[] = ':if ([:len [/ip firewall mangle find where comment='.$this->quote($mangleComment).']] = 0) do={ /ip firewall mangle add action=mark-routing chain=prerouting comment='.$this->quote($mangleComment).' dst-address-list='.$this->quote('speedtest').' new-routing-mark='.$this->quote($table).' passthrough=yes }';
        $lines[] = ':if ([:len [/ip route find where comment='.$this->quote($routeComment).']] = 0) do={ /ip route add dst-address='.$this->quote('0.0.0.0/0').' gateway='.$this->quote($gateway).' routing-table='.$this->quote($table).' distance=1 check-gateway=ping comment='.$this->quote($routeComment).' }';

        return implode("\n", $lines)."\n";
    }

    private function addressListAdd(string $list, string $address, ?string $comment = null): string
    {
        $condition = 'list='.$this->quote($list).' and address='.$this->quote($address);
        $add = '/ip firewall address-list add address='.$this->quote($address).' list='.$this->quote($list);

        if ($comment !== null) {
            $add .= ' comment='.$this->quote($comment);
        }

        return ':if ([:len [/ip firewall address-list find where '.$condition.']] = 0) do={ '.$add.' }';
    }

    private function quote(string $value): string
    {
        $value = str_replace(["\r", "\n"], ' ', $value);

        return '"'.str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], $value).'"';
    }
